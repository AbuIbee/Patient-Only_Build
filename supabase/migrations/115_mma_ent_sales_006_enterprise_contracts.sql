-- OWNER DIRECTIVE MMA-ENT-SALES-006 Phase F3 — "Complete the
-- application-side contract lifecycle... Inspect whether the existing
-- application already has document signing or agreement
-- infrastructure... An external e-signature provider must not be
-- treated as universally mandatory if the Platform Owner has an
-- approved, valid manual or electronic contract execution procedure.
-- If no approved legal terms or permissible execution process exists,
-- complete the workflow infrastructure and leave the particular
-- signature prerequisite correctly BLOCKED. Do not create fake
-- contract signatures."
--
-- A repo-wide search (package.json, every migration, every src file)
-- found NO existing e-signature provider integration and NO existing
-- contract/agreement/BAA/signature table or storage convention. This
-- migration builds the real, auditable contract lifecycle
-- infrastructure the directive asks for; the one thing it correctly
-- does NOT do is fabricate a signature or claim an executed agreement
-- exists. "Executed" is only ever recorded when the Platform Owner
-- explicitly supplies BOTH a real execution method (e.g. "DocuSign
-- envelope #..." or "wet signature, scanned, stored at ...") AND an
-- evidence reference -- this records the owner's own attestation to a
-- real external process, auditable and attributable, never a
-- fabricated signature generated by this system.
CREATE TABLE IF NOT EXISTS enterprise_contracts (
  id                        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  quote_id                  UUID NOT NULL REFERENCES sales_quotes(id),
  contract_type             TEXT NOT NULL CHECK (contract_type IN ('saas_license', 'baa', 'dpa')),
  template_version          TEXT NOT NULL,
  signatory_name            TEXT NOT NULL,
  signatory_title           TEXT,
  status                    TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'presented', 'executed', 'void')),
  presented_at              TIMESTAMP WITH TIME ZONE,
  execution_method          TEXT,
  execution_evidence_reference TEXT,
  executed_by               UUID REFERENCES profiles(id),
  executed_at               TIMESTAMP WITH TIME ZONE,
  voided_reason             TEXT,
  created_by                UUID NOT NULL REFERENCES profiles(id),
  created_at                TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  updated_at                TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  -- One contract of each type per quote -- a revised quote (migration
  -- 107's supersedes_quote_id) gets its own contract, never edits an
  -- existing one's terms in place.
  UNIQUE (quote_id, contract_type)
);
ALTER TABLE enterprise_contracts ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Platform Owner can view all enterprise contracts"
  ON enterprise_contracts FOR SELECT TO authenticated
  USING (is_platform_owner());

-- The applicant/director whose application or amendment request
-- references this quote may read their own contract once it has been
-- presented (not while still a Platform Owner-only draft) -- the same
-- dual ownership path migration 114 established for billing.
CREATE POLICY "An applicant or amendment-org director can view a presented contract"
  ON enterprise_contracts FOR SELECT TO authenticated
  USING (
    status <> 'draft'
    AND (
      EXISTS (
        SELECT 1 FROM professional_applications pa
        WHERE pa.applicant_user_id = auth.uid() AND pa.application_details->>'originatingQuoteId' = enterprise_contracts.quote_id::text
      )
      OR EXISTS (
        SELECT 1 FROM organization_amendment_requests oar
        WHERE oar.resulting_quote_id = enterprise_contracts.quote_id AND is_active_org_director(oar.organization_id)
      )
    )
  );

CREATE OR REPLACE FUNCTION platform_owner_create_contract(
  p_quote_id UUID, p_contract_type TEXT, p_template_version TEXT, p_signatory_name TEXT, p_signatory_title TEXT
) RETURNS enterprise_contracts
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_row enterprise_contracts;
BEGIN
  IF NOT is_platform_owner() THEN RAISE EXCEPTION 'Only the Platform Owner may create a contract record'; END IF;
  IF NOT EXISTS (SELECT 1 FROM sales_quotes WHERE id = p_quote_id) THEN RAISE EXCEPTION 'No such quote'; END IF;
  IF btrim(coalesce(p_template_version, '')) = '' THEN RAISE EXCEPTION 'A template version is required -- never left blank or invented by this system'; END IF;
  IF btrim(coalesce(p_signatory_name, '')) = '' THEN RAISE EXCEPTION 'A signatory name is required'; END IF;

  INSERT INTO enterprise_contracts (quote_id, contract_type, template_version, signatory_name, signatory_title, created_by)
  VALUES (p_quote_id, p_contract_type, p_template_version, p_signatory_name, p_signatory_title, auth.uid())
  RETURNING * INTO v_row;

  RETURN v_row;
END;
$$;
REVOKE ALL ON FUNCTION platform_owner_create_contract(UUID, TEXT, TEXT, TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION platform_owner_create_contract(UUID, TEXT, TEXT, TEXT, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION platform_owner_present_contract(p_contract_id UUID)
RETURNS enterprise_contracts
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_row enterprise_contracts;
BEGIN
  IF NOT is_platform_owner() THEN RAISE EXCEPTION 'Only the Platform Owner may present a contract'; END IF;
  SELECT * INTO v_row FROM enterprise_contracts WHERE id = p_contract_id FOR UPDATE;
  IF v_row.id IS NULL THEN RAISE EXCEPTION 'No such contract'; END IF;
  IF v_row.status <> 'draft' THEN RAISE EXCEPTION 'Only a draft contract can be presented'; END IF;

  UPDATE enterprise_contracts SET status = 'presented', presented_at = now(), updated_at = now()
  WHERE id = p_contract_id RETURNING * INTO v_row;
  RETURN v_row;
END;
$$;
REVOKE ALL ON FUNCTION platform_owner_present_contract(UUID) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION platform_owner_present_contract(UUID) TO authenticated;

-- The ONLY path from 'presented' to 'executed'. Deliberately requires
-- BOTH a real execution method and a real evidence reference -- this
-- is an owner ATTESTATION to a real external process (their own
-- approved manual or electronic procedure, per the directive), never
-- a signature generated or verified by this system. "The decision and
-- evidence are real and auditable" is satisfied by recording exactly
-- what the owner provides, attributed to them, timestamped -- nothing
-- here claims to have independently verified the underlying signature
-- itself.
CREATE OR REPLACE FUNCTION platform_owner_record_contract_execution(
  p_contract_id UUID, p_execution_method TEXT, p_execution_evidence_reference TEXT
) RETURNS enterprise_contracts
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_row enterprise_contracts;
BEGIN
  IF NOT is_platform_owner() THEN RAISE EXCEPTION 'Only the Platform Owner may record a contract execution'; END IF;
  IF btrim(coalesce(p_execution_method, '')) = '' THEN RAISE EXCEPTION 'An execution method is required -- this system never fabricates one'; END IF;
  IF btrim(coalesce(p_execution_evidence_reference, '')) = '' THEN RAISE EXCEPTION 'An evidence reference is required -- this system never fabricates one'; END IF;

  SELECT * INTO v_row FROM enterprise_contracts WHERE id = p_contract_id FOR UPDATE;
  IF v_row.id IS NULL THEN RAISE EXCEPTION 'No such contract'; END IF;
  IF v_row.status <> 'presented' THEN RAISE EXCEPTION 'Only a presented contract can be marked executed'; END IF;

  UPDATE enterprise_contracts SET
    status = 'executed', execution_method = p_execution_method, execution_evidence_reference = p_execution_evidence_reference,
    executed_by = auth.uid(), executed_at = now(), updated_at = now()
  WHERE id = p_contract_id RETURNING * INTO v_row;
  RETURN v_row;
END;
$$;
REVOKE ALL ON FUNCTION platform_owner_record_contract_execution(UUID, TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION platform_owner_record_contract_execution(UUID, TEXT, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION platform_owner_void_contract(p_contract_id UUID, p_reason TEXT)
RETURNS enterprise_contracts
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_row enterprise_contracts;
BEGIN
  IF NOT is_platform_owner() THEN RAISE EXCEPTION 'Only the Platform Owner may void a contract'; END IF;
  IF btrim(coalesce(p_reason, '')) = '' THEN RAISE EXCEPTION 'A reason is required'; END IF;
  SELECT * INTO v_row FROM enterprise_contracts WHERE id = p_contract_id FOR UPDATE;
  IF v_row.id IS NULL THEN RAISE EXCEPTION 'No such contract'; END IF;
  IF v_row.status = 'void' THEN RAISE EXCEPTION 'Already void'; END IF;

  UPDATE enterprise_contracts SET status = 'void', voided_reason = p_reason, updated_at = now()
  WHERE id = p_contract_id RETURNING * INTO v_row;
  RETURN v_row;
END;
$$;
REVOKE ALL ON FUNCTION platform_owner_void_contract(UUID, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION platform_owner_void_contract(UUID, TEXT) TO authenticated;

-- OWNER DIRECTIVE Phase G1 — "Verify independently: ... Executed
-- required agreement." Backward-compatible by construction: a quote
-- that has NO contract record at all (every quote tested so far in
-- this engagement, since no contract requirement has ever been
-- configured) behaves exactly as before -- this adds a gate, never a
-- requirement, for commercial paths the owner has not opted into a
-- contract for. The moment the owner DOES create a contract for a
-- quote, activation (and amendment application) genuinely waits for
-- it to be executed.
CREATE OR REPLACE FUNCTION activate_enterprise_license_from_quote(p_quote_id UUID)
RETURNS organization_licenses
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_quote sales_quotes;
  v_app professional_applications;
  v_license organization_licenses;
  v_prefix TEXT;
  v_year INTEGER;
  v_seq INTEGER;
  v_license_number TEXT;
BEGIN
  SELECT * INTO v_quote FROM sales_quotes WHERE id = p_quote_id;
  IF v_quote.id IS NULL THEN
    RAISE EXCEPTION 'No such quote (%)', p_quote_id;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM enterprise_billing_accounts eba WHERE eba.quote_id = p_quote_id AND eba.status = 'active'
  ) THEN
    RAISE EXCEPTION 'No confirmed-paid Enterprise billing account exists for quote % -- license cannot activate without confirmed payment', p_quote_id;
  END IF;

  IF EXISTS (
    SELECT 1 FROM enterprise_contracts ec WHERE ec.quote_id = p_quote_id AND ec.status NOT IN ('executed', 'void')
  ) THEN
    RAISE EXCEPTION 'A required agreement for quote % has not yet been executed -- license cannot activate until it is', p_quote_id;
  END IF;

  SELECT * INTO v_app FROM professional_applications
  WHERE application_details->>'originatingQuoteId' = p_quote_id::text
    AND status = 'approved' AND target_organization_id IS NOT NULL
  ORDER BY platform_owner_approved_at DESC
  LIMIT 1;
  IF v_app.id IS NULL THEN
    RAISE EXCEPTION 'No approved Director application with an organization references quote % yet -- license cannot activate before approval', p_quote_id;
  END IF;

  SELECT * INTO v_license FROM organization_licenses WHERE organization_id = v_app.target_organization_id FOR UPDATE;
  IF v_license.id IS NULL THEN
    RAISE EXCEPTION 'No license configuration row exists for organization %', v_app.target_organization_id;
  END IF;

  IF v_license.status = 'active' AND v_license.license_number IS NOT NULL THEN
    RETURN v_license;
  END IF;

  v_prefix := CASE v_quote.package_type
    WHEN 'integrated_care' THEN 'MMA-FE'
    WHEN 'therapist' THEN 'MMA-TE'
    ELSE NULL
  END;
  IF v_prefix IS NULL THEN
    RAISE EXCEPTION 'Unrecognized package type % on quote % -- cannot issue a license number', v_quote.package_type, p_quote_id;
  END IF;

  v_year := EXTRACT(YEAR FROM now())::INTEGER;

  INSERT INTO enterprise_license_sequences (year, prefix, next_value)
  VALUES (v_year, v_prefix, 1)
  ON CONFLICT (year, prefix) DO UPDATE SET next_value = enterprise_license_sequences.next_value + 1
  RETURNING next_value INTO v_seq;

  v_license_number := v_prefix || '-' || v_year || '-' || lpad(v_seq::text, 6, '0');

  UPDATE organization_licenses SET
    license_number = v_license_number,
    licensed_seats = v_quote.proposed_licensed_seats,
    covered_patient_capacity = v_quote.proposed_covered_patient_capacity,
    annual_license_fee = v_quote.annual_license_fee,
    status = 'active',
    activated_by = NULL,
    activated_at = now(),
    updated_at = now()
  WHERE id = v_license.id
  RETURNING * INTO v_license;

  INSERT INTO professional_application_events (application_id, event_type, actor_user_id, actor_role, from_status, to_status, notes)
  VALUES (v_app.id, 'enterprise_license_activated', NULL, 'system', v_app.status, v_app.status,
    'License ' || v_license_number || ' activated for organization ' || v_app.target_organization_id || ' following confirmed Enterprise payment');

  RETURN v_license;
END;
$$;
REVOKE ALL ON FUNCTION activate_enterprise_license_from_quote(UUID) FROM PUBLIC, authenticated, anon;
GRANT EXECUTE ON FUNCTION activate_enterprise_license_from_quote(UUID) TO service_role;

-- Same gate added to the amendment-application path -- an amendment
-- quote with an unexecuted required contract cannot apply either.
CREATE OR REPLACE FUNCTION apply_organization_amendment_from_quote(p_quote_id UUID)
RETURNS organization_amendment_requests
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_request organization_amendment_requests;
  v_quote sales_quotes;
  v_license organization_licenses;
BEGIN
  SELECT * INTO v_request FROM organization_amendment_requests WHERE resulting_quote_id = p_quote_id AND status = 'quoted' FOR UPDATE;
  IF v_request.id IS NULL THEN
    RAISE EXCEPTION 'No quoted amendment request references quote %', p_quote_id;
  END IF;
  IF v_request.request_type = 'cancellation' THEN
    RAISE EXCEPTION 'Cancellation requests are applied directly by the Platform Owner, never through a paid checkout';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM enterprise_billing_accounts eba WHERE eba.quote_id = p_quote_id AND eba.status = 'active'
  ) THEN
    RAISE EXCEPTION 'No confirmed-paid Enterprise billing account exists for amendment quote % -- cannot apply without confirmed payment', p_quote_id;
  END IF;

  IF EXISTS (
    SELECT 1 FROM enterprise_contracts ec WHERE ec.quote_id = p_quote_id AND ec.status NOT IN ('executed', 'void')
  ) THEN
    RAISE EXCEPTION 'A required agreement for amendment quote % has not yet been executed -- cannot apply until it is', p_quote_id;
  END IF;

  SELECT * INTO v_quote FROM sales_quotes WHERE id = p_quote_id;
  IF v_quote.id IS NULL THEN RAISE EXCEPTION 'No such quote %', p_quote_id; END IF;

  SELECT * INTO v_license FROM organization_licenses WHERE organization_id = v_request.organization_id FOR UPDATE;
  IF v_license.id IS NULL THEN RAISE EXCEPTION 'No license configuration row exists for organization %', v_request.organization_id; END IF;

  UPDATE organization_licenses SET
    licensed_seats = v_quote.proposed_licensed_seats,
    covered_patient_capacity = v_quote.proposed_covered_patient_capacity,
    annual_license_fee = v_quote.annual_license_fee,
    status = 'active',
    updated_at = now()
  WHERE id = v_license.id;

  UPDATE organization_amendment_requests SET status = 'completed', completed_at = now(), updated_at = now()
  WHERE id = v_request.id RETURNING * INTO v_request;

  RETURN v_request;
END;
$$;
REVOKE ALL ON FUNCTION apply_organization_amendment_from_quote(UUID) FROM PUBLIC, authenticated, anon;
GRANT EXECUTE ON FUNCTION apply_organization_amendment_from_quote(UUID) TO service_role;
